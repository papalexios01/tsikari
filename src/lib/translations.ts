export function translate(value: string): string {
  const exact = greek.get(value);
  if (exact) return exact;
  const match = /^(\d+) photos?$/.exec(value);
  if (match) return match[1] + ' φωτογραφίες';
  const nights = /^(\d+) nights? selected$/.exec(value);
  if (nights) return nights[1] + (nights[1] === '1' ? ' διανυκτέρευση' : ' διανυκτερεύσεις');
  const upTo = /^Up to (\d+) guests$/.exec(value);
  if (upTo) return 'Έως ' + upTo[1] + ' άτομα';
  return value;
}
